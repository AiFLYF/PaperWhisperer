// ==========================================================================
// Bounds
// ==========================================================================
//
// Every number below is a ceiling on how long the browser will wait and how
// much it will read. They exist because the failure they prevent is the one
// that cannot be recovered from: a request that never settles holds a spinner
// up for ever, and a spinner that never clears is indistinguishable from work
// that is still running. A bound is what lets the interface say "this died" —
// which is only possible if something is guaranteed to eventually happen.
//
// The values are not tuning knobs chosen for taste. Each one answers a specific
// question about the slowest thing the server can legitimately do.
export const REQUEST_TIMEOUTS_MS = {
    /** A liveness probe the page makes once on load and then forgets. */
    health: 10000,
    /** A plain JSON round trip: search, queue save, health, evidence. */
    default: 30000,
    /** A model call with no streaming body. Longer, but still bounded. */
    generation: 120000,
    /**
     * A document analysis. The server streams sections as it produces them, so
     * this is a *stall* budget measured between events rather than a total:
     * see `streamStallTimeoutMs`. The total here is the backstop for a
     * connection that stays open and produces nothing at all.
     */
    analysis: 900000,
    /** An import from a remote URL, which includes a network fetch. */
    import: 300000
};

export const RESPONSE_SIZE_CAPS_BYTES = {
    /** A JSON body. Large enough for a full paper's evidence payload. */
    json: 32 * 1024 * 1024,
    /**
     * A single SSE event. The bound that matters most, because a stream has
     * no declared length: without it, one event claiming to be a gigabyte is
     * read into memory before anything can object. An event that exceeds this
     * is a protocol violation, not a big document.
     */
    streamEvent: 8 * 1024 * 1024,
    /**
     * The unread portion of a single response. A cap on the *stream* rather
     * than on one event, so a stream that dribbles out many oversized events
     * is still bounded.
     */
    streamTotal: 64 * 1024 * 1024
};

/**
 * How long a stream may produce nothing before it is treated as dead.
 *
 * A two-minute parse and a dead connection look identical if the only signal
 * is "no data yet". This is the number that tells them apart: past it, with no
 * byte and no event, the request is declared stalled and the user is told so
 * with a re-attach option rather than being left watching a spinner.
 *
 * Deliberately much longer than any plausible gap between sections of a real
 * analysis. A parse that stalls here is stalled for a reason, and pretending
 * otherwise would reintroduce the exact defect this exists to remove.
 */
export const STREAM_STALL_TIMEOUT_MS = 120000;

/**
 * How long a *resumed* stream waits before the resync is declared failed.
 *
 * Shorter than `STREAM_STALL_TIMEOUT_MS` on purpose: re-attaching is cheap and
 * the client already knows the work may be nearly over, so a slow re-attach is
 * more likely to be a problem than a long parse.
 */
export const RESYNC_TIMEOUT_MS = 20000;

