// ==========================================================================
// The failure taxonomy
// ==========================================================================
//
// A backend failure is not one thing. `build_error_payload` in
// `paperwhisperer/core/errors.py` puts a stable machine-readable `code` next to
// a Chinese sentence on every failure, and that split is what makes this
// section possible: the sentence is prose a human reads, the `code` is the API.
// Every failure state in this front end is therefore derived from the code and
// never from pattern-matching the prose — a server-side rewording cannot turn a
// terminal error into something that looks retryable, and a sentence that
// happens to contain "限流" cannot do it either.
export const FAILURE_KINDS = {
    /** The request has not finished. Never presented as a failure. */
    PENDING: 'pending',
    /** It failed, and the same request has a real chance of succeeding later. */
    RETRYABLE: 'retryable',
    /** It failed and re-issuing it would fail identically. Names the cause. */
    TERMINAL: 'terminal',
    /** The server could not be reached at all. Distinct from every kind above. */
    UNREACHABLE: 'unreachable'
};

//: The kind assumed for a `code` this build has never been told about.
